package com.kite.di.processor.validate

import com.kite.di.processor.model.ClasspathIndex
import com.kite.di.processor.model.Severity
import org.junit.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * `implementation` is not transitive, so a module reached only through another
 * module's `implementation` never reaches the application's compile classpath: its
 * registry is absent from the merge, the build passes, and the app dies on the device.
 * Each module records which modules it resolved keys from; this is where the
 * application checks that all of them arrived.
 */
class MergeValidatorTest {

    @Test
    fun `a required module that is merged is fine`() {
        val classpath = ClasspathIndex(
            modules = setOf(":feature:list", ":data"),
            requires = mapOf(":feature:list" to listOf(":data")),
        )

        assertEquals(emptyList(), MergeValidator.validate(classpath, selfModule = ":app"))
    }

    @Test
    fun `a required module that is not merged is an error naming both and the fix`() {
        val classpath = ClasspathIndex(
            modules = setOf(":feature:list"),
            requires = mapOf(":feature:list" to listOf(":data")),
        )

        val error = MergeValidator.validate(classpath, selfModule = ":app").single()
        assertEquals(Severity.ERROR, error.severity)
        assertTrue("Module :data is missing from the merged graph" in error.message, error.message)
        assertTrue(":feature:list resolves keys from it" in error.message, error.message)
        assertTrue("""api(project(":data"))""" in error.message, error.message)
    }

    @Test
    fun `one missing module is reported once, listing every module that needs it`() {
        val classpath = ClasspathIndex(
            modules = setOf(":feature:list", ":feature:details"),
            requires = mapOf(
                ":feature:details" to listOf(":data"),
                ":feature:list" to listOf(":data"),
            ),
        )

        val error = MergeValidator.validate(classpath, selfModule = ":app").single()
        assertTrue(":feature:list resolves keys from it" in error.message, error.message)
        assertTrue(":feature:details resolves keys from it" in error.message, error.message)
    }

    @Test
    fun `the application's own module is never missing from its own merge`() {
        // Its registry is generated by this very compilation, so it is not on the
        // classpath the check reads.
        val classpath = ClasspathIndex(
            modules = setOf(":feature:list"),
            requires = mapOf(":feature:list" to listOf(":app")),
        )

        assertEquals(emptyList(), MergeValidator.validate(classpath, selfModule = ":app"))
    }

    @Test
    fun `a module whose graph ships unmerged is an error even when nothing recorded a demand`() {
        // The `Kite.get<T>()` / `by injected()` case: the demand is an expression inside a
        // function body, so no metadata could have carried it. What the build can see is
        // that the module is in the app and its registry is not.
        val classpath = ClasspathIndex(modules = setOf(":lookup"), requires = mapOf(":lookup" to emptyList()))

        val error = MergeValidator.validate(classpath, ":app", unmergedModules = listOf(":data")).single()
        assertEquals(Severity.ERROR, error.severity)
        assertTrue("Module :data has a graph this application does not merge" in error.message, error.message)
        assertTrue("""api(project(":data"))""" in error.message, error.message)
    }

    @Test
    fun `a module that both ships unmerged and was recorded is reported once`() {
        val classpath = ClasspathIndex(
            modules = setOf(":feature"),
            requires = mapOf(":feature" to listOf(":data")),
        )

        val error = MergeValidator.validate(classpath, ":app", unmergedModules = listOf(":data")).single()
        assertTrue(":feature resolves keys from it" in error.message, error.message)
    }

    @Test
    fun `a module that is merged is never accused of shipping unmerged`() {
        val classpath = ClasspathIndex(modules = setOf(":feature", ":data"))

        assertEquals(emptyList(), MergeValidator.validate(classpath, ":app", unmergedModules = listOf(":data")))
    }

    @Test
    fun `a module built by an older Kite, which records nothing, is not accused`() {
        val classpath = ClasspathIndex(modules = setOf(":legacy"), requires = mapOf(":legacy" to emptyList()))

        assertEquals(emptyList(), MergeValidator.validate(classpath, selfModule = ":app"))
    }
}
