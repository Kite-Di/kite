package com.kite.di.processor.codegen

import com.kite.di.graph.ScopeDef
import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec

/**
 * Emits how the scopes this module names are opened and closed (ADR 15 §4):
 *
 * ```kotlin
 * @Scoped(SessionCart::class, "Session")   // GraphRules.kt — the whole declaration
 *
 * openSession()                             // at login
 * private val cart by sessionCart()         // like any other accessor
 * closeSession()                            // at logout
 * ```
 *
 * Nothing about the scope is written twice: its name is the decision, and its level
 * is derived from the name ([ScopeDef.custom]), so every module that names "Session"
 * opens the same one.
 */
object ScopeGenerator {

    private val KITE = ClassName("com.kite.di.runtime", "Kite")
    private val GENERATED_API = ClassName("com.kite.di.runtime", "KiteGeneratedApi")
    private val OPT_IN = ClassName("kotlin", "OptIn")

    fun scopesFile(scopes: List<ScopeDef>, packageName: String, moduleName: String): FileSpec {
        val file = FileSpec.builder(packageName, sanitizeModuleName(moduleName) + "_Scopes")
            .addFileComment("Generated by the Kite processor for module %L — do not edit.", moduleName)
            .addAnnotation(AnnotationSpec.builder(OPT_IN).addMember("%T::class", GENERATED_API).build())
        for (scope in scopes.sortedBy { it.name }) {
            val suffix = scope.name.replaceFirstChar(Char::uppercaseChar)
            file.addFunction(
                FunSpec.builder("open$suffix")
                    .addKdoc(
                        "Opens the %L scope. Opening it again replaces the open one; everything in it is new.",
                        scope.name,
                    )
                    .addStatement("%T.openScope(%S, %L)", KITE, scope.name, scope.level)
                    .build(),
            )
            file.addFunction(
                FunSpec.builder("close$suffix")
                    .addKdoc("Closes the %L scope and drops everything in it.", scope.name)
                    .addStatement("%T.closeScope(%S)", KITE, scope.name)
                    .build(),
            )
        }
        return file.build()
    }
}
